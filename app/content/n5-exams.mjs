function makeForm(letter,v,g,passages,listening){
 const id=`N5-${letter}`;
 const vocabulary=v.map(([prompt,answer,wrong,explanation],i)=>choose(`${id}-v${i+1}`,i<10?'kanji':'vocabulary',prompt,answer,wrong,explanation));
 const gr=g.map(([prompt,answer,wrong,explanation],i)=>choose(`${id}-g${i+1}`,'grammar',prompt,answer,wrong,explanation));
 const reading=passages.flatMap(([title,passage,qs],p)=>qs.map(([prompt,answer,wrong],n)=>choose(`${id}-r${p*3+n+1}`,'reading',prompt,answer,wrong,`請回到〈${title}〉定位資訊。正確答案：${answer}。`,{passage,passageTitle:title})));
 const listen=listening.map(([transcript,prompt,answer,wrong,explanation],i)=>choose(`${id}-l${i+1}`,'listening',prompt,answer,wrong,explanation,{transcript}));
 return {id,level:'N5',title:`N5 自編完整分科卷 ${letter}`,sections:[{id:'vocabulary',title:'文字・語彙',minutes:20,questions:vocabulary},{id:'grammar-reading',title:'文法・讀解',minutes:40,questions:[...gr,...reading]},{id:'listening',title:'聽解',minutes:30,questions:listen}]};
}
